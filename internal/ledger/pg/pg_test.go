func TestPlaceholders(t *testing.T) {
	cases := map[string]string{
		`SELECT 1`:                                                               `SELECT 1`,
		`SELECT * FROM t WHERE a = ? AND b = ?`:                                  `SELECT * FROM t WHERE a = $1 AND b = $2`,
		`INSERT INTO t(a, b) VALUES(?,?)`:                                        `INSERT INTO t(a, b) VALUES($1,$2)`,
		`SELECT * FROM t WHERE a = '?' AND b = ?`:                                `SELECT * FROM t WHERE a = '?' AND b = $1`,
		`SELECT * FROM t WHERE a = 'it''s ?' AND b = ?`:                          `SELECT * FROM t WHERE a = 'it''s ?' AND b = $1`,
		`SELECT "col?" FROM t WHERE x = ?`:                                       `SELECT "col?" FROM t WHERE x = $1`,
		"SELECT a -- what? \nFROM t WHERE b = ?":                                 "SELECT a -- what? \nFROM t WHERE b = $1",
		`SELECT a /* ? */ FROM t WHERE b = ? ORDER BY c LIMIT ?`:                 `SELECT a /* ? */ FROM t WHERE b = $1 ORDER BY c LIMIT $2`,
		`UPDATE t SET x = ? WHERE y LIKE ? ESCAPE '\'`:                           `UPDATE t SET x = $1 WHERE y LIKE $2 ESCAPE '\'`,
		`INSERT INTO t(a) VALUES(?) ON CONFLICT(a) DO UPDATE SET b = excluded.b`: `INSERT INTO t(a) VALUES($1) ON CONFLICT(a) DO UPDATE SET b = excluded.b`,
		`SELECT '{"k":"?"}', ?`:                                                  `SELECT '{"k":"?"}', $1`,
	}
	for in, want := range cases {
		if got := Placeholders(in); got != want {
			t.Errorf("Placeholders(%q)\n got %q\nwant %q", in, got, want)
		}
	}
}

func TestSchema(t *testing.T) {
	in := "CREATE TABLE IF NOT EXISTS events (\n  seq INTEGER PRIMARY KEY AUTOINCREMENT,\n  github_id INTEGER NOT NULL DEFAULT 0, -- INTEGER here is a comment\n  data TEXT NOT NULL,\n  ciphertext BLOB NOT NULL,\n  blobby TEXT NOT NULL DEFAULT 'blob INTEGER'\n);"
	got := Schema(in)
	for _, want := range []string{"seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "github_id BIGINT NOT NULL DEFAULT 0, -- INTEGER here is a comment", "ciphertext BYTEA NOT NULL", "DEFAULT 'blob INTEGER'"} {
		if !contains(got, want) {
			t.Errorf("Schema lacks %q:\n%s", want, got)
		}
	}
	if contains(got, "AUTOINCREMENT") || contains(got, " BLOB ") || contains(got, "github_id INTEGER") {
		t.Errorf("sqlite syntax left: %s", got)
	}
}

func TestURLHelpers(t *testing.T) {
	if !IsURL("postgres://u:p@h/db") || !IsURL("postgresql://h/db") || IsURL("/tmp/ore.db") || IsURL("sqlite:///tmp/ore.db") {
		t.Fatal("IsURL")
	}
	if got := Redact("postgres://ore:s3cret@db:5432/ore?sslmode=disable"); got != "postgres://ore:REDACTED@db:5432/ore?sslmode=disable" {
		t.Fatalf("Redact %q", got)
	}
	if got := Redact("postgres://db/ore"); got != "postgres://db/ore" {
		t.Fatalf("Redact without password %q", got)
	}
	got := WithSearchPath("postgres://u:p@h/db?sslmode=disable", "ore_test_1")
	if !contains(got, "search_path=ore_test_1") || !contains(got, "sslmode=disable") {
		t.Fatalf("WithSearchPath %q", got)
	}
	if a, b := TestSchemaName(), TestSchemaName(); a == b || len(a) < 12 {
		t.Fatal("schema names must be unique")
	}
	if QuoteIdent(`a"b`) != `"a""b"` {
		t.Fatal("QuoteIdent")
	}
}

func contains(s, sub string) bool {
	return len(sub) == 0 || (len(s) >= len(sub) && indexOf(s, sub) >= 0)
}

func indexOf(s, sub string) int {
	for i := 0; i+len(sub) <= len(s); i++ {
		if s[i:i+len(sub)] == sub {
			return i
		}
	}
	return -1
}
