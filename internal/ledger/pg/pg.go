// Package pg is the Postgres dialect for the ledger (ADR 0006: exactly two SQL
// targets). It registers the pgx stdlib driver and rewrites the SQL the rest
// of Ore writes for SQLite so the same statements and the same embedded
// migrations run on Postgres: `?` placeholders become `$n`, AUTOINCREMENT
// becomes an identity column, BLOB becomes BYTEA. Timestamps stay TEXT.
package pg

import (
	"crypto/rand"
	"encoding/hex"
	"errors"
	"net/url"
	"regexp"
	"strconv"
	"strings"

	"github.com/jackc/pgx/v5/pgconn"
	_ "github.com/jackc/pgx/v5/stdlib" // registers the "pgx" database/sql driver
)

// Driver is the database/sql driver name.
const Driver = "pgx"

// IsURL reports whether target is a Postgres connection URL.
func IsURL(target string) bool {
	return strings.HasPrefix(target, "postgres://") || strings.HasPrefix(target, "postgresql://")
}

// Placeholders rewrites `?` parameters to `$1..$n`, leaving string literals,
// quoted identifiers and comments alone. A query without `?` is returned as is.
func Placeholders(q string) string {
	if !strings.Contains(q, "?") {
		return q
	}
	n := 0
	return rewriteCode(q, func(code string) string {
		var b strings.Builder
		for i := 0; i < len(code); i++ {
			if code[i] == '?' {
				n++
				b.WriteByte('$')
				b.WriteString(strconv.Itoa(n))
				continue
			}
			b.WriteByte(code[i])
		}
		return b.String()
	})
}

// rewriteCode applies fn to the parts of q that are SQL code, copying string
// literals, quoted identifiers and comments through unchanged.
func rewriteCode(q string, fn func(code string) string) string {
	var b strings.Builder
	b.Grow(len(q) + 16)
	start := 0
	flush := func(end int) {
		if end > start {
			b.WriteString(fn(q[start:end]))
		}
	}
	for i := 0; i < len(q); i++ {
		c := q[i]
		switch {
		case c == '\'' || c == '"':
			flush(i)
			j := i + 1
			for j < len(q) {
				if q[j] == c {
					if j+1 < len(q) && q[j+1] == c {
						j += 2
						continue
					}
					break
				}
				j++
			}
			if j >= len(q) {
				j = len(q) - 1
			}
			b.WriteString(q[i : j+1])
			i = j
			start = i + 1
		case c == '-' && i+1 < len(q) && q[i+1] == '-':
			flush(i)
			j := strings.IndexByte(q[i:], '\n')
			if j < 0 {
				b.WriteString(q[i:])
				return b.String()
			}
			b.WriteString(q[i : i+j])
			i += j - 1
			start = i + 1
		case c == '/' && i+1 < len(q) && q[i+1] == '*':
			flush(i)
			j := strings.Index(q[i+2:], "*/")
			if j < 0 {
				b.WriteString(q[i:])
				return b.String()
			}
			b.WriteString(q[i : i+2+j+2])
			i += 2 + j + 1
			start = i + 1
		}
	}
	flush(len(q))
	return b.String()
}

var (
	autoincRE = regexp.MustCompile(`(?i)\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b`)
	integerRE = regexp.MustCompile(`(?i)\bINTEGER\b`)
	blobRE    = regexp.MustCompile(`(?i)\bBLOB\b`)
)

// Schema rewrites SQLite DDL (the embedded migrations) for Postgres:
// AUTOINCREMENT becomes an identity column, INTEGER becomes BIGINT (SQLite
// integers are 64-bit; GitHub ids and byte sizes exceed int4) and BLOB
// becomes BYTEA. Literals and comments are left alone.
func Schema(ddl string) string {
	return rewriteCode(ddl, func(code string) string {
		out := autoincRE.ReplaceAllString(code, "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
		out = integerRE.ReplaceAllString(out, "BIGINT")
		return blobRE.ReplaceAllString(out, "BYTEA")
	})
}

// IsUniqueViolation reports whether err is a unique-constraint violation (SQLSTATE 23505).
func IsUniqueViolation(err error) bool {
	var pgErr *pgconn.PgError
	return errors.As(err, &pgErr) && pgErr.Code == "23505"
}

// IsAuthError reports whether err is an authentication failure (SQLSTATE 28xxx).
func IsAuthError(err error) bool {
	var pgErr *pgconn.PgError
	return errors.As(err, &pgErr) && strings.HasPrefix(pgErr.Code, "28")
}

// Redact hides the password in a connection URL for logs and `ore config`.
func Redact(target string) string {
	u, err := url.Parse(target)
	if err != nil || u.User == nil {
		return target
	}
	if _, has := u.User.Password(); has {
		u.User = url.UserPassword(u.User.Username(), "REDACTED")
	}
	return u.String()
}

// WithSearchPath returns the URL with search_path set to schema, so every
// unqualified table name resolves there (test isolation: one schema per test).
func WithSearchPath(target, schema string) string {
	u, err := url.Parse(target)
	if err != nil {
		return target
	}
	q := u.Query()
	q.Set("search_path", schema)
	u.RawQuery = q.Encode()
	return u.String()
}

// TestSchemaName returns a fresh schema name for an isolated test database.
func TestSchemaName() string {
	var b [6]byte
	rand.Read(b[:])
	return "ore_test_" + hex.EncodeToString(b[:])
}

// QuoteIdent quotes an identifier for Postgres.
func QuoteIdent(s string) string { return `"` + strings.ReplaceAll(s, `"`, `""`) + `"` }
