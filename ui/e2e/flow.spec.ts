import { expect, test } from '@playwright/test'
import { api, unfocus } from './api'

test.describe('the main flow', () => {
  test('home lists the repository and recent activity', async ({ page }) => {
    await page.goto('/app/')
    await expect(page.getByRole('heading', { name: 'Repositories' })).toBeVisible()
    await expect(page.getByRole('link', { name: /acme\/app/ }).first()).toBeVisible()
    await expect(page.getByText('Recent activity')).toBeVisible()
    await expect(page.locator('.event-row').first()).toBeVisible()
  })

  test('browse code: tree, README, a file with line anchors, history and a commit diff', async ({ page }) => {
    await page.goto('/app/acme/app')
    await expect(page.locator('.repo-head h1')).toContainText('app')
    // README renders as Markdown, sanitized.
    await expect(page.locator('.prose h1', { hasText: 'app' })).toBeVisible()
    expect(await page.locator('.prose script').count()).toBe(0)
    // Open a file from the tree.
    await page.getByRole('button', { name: 'main.go' }).first().click()
    await expect(page).toHaveURL(/\/blob\/main\/main\.go$/)
    await expect(page.locator('.file-view')).toContainText('func greeting()')
    await expect(page.locator('.tok-keyword').first()).toBeVisible()
    // Line anchors.
    await page.getByRole('link', { name: 'Line 9' }).click()
    await expect(page).toHaveURL(/#L9$/)
    await expect(page.locator('#L9')).toHaveClass(/hl/)
    // Find file with "t".
    await unfocus(page)
    await page.keyboard.press('t')
    await page.getByLabel('File path').fill('guide')
    await page.keyboard.press('Enter')
    await expect(page).toHaveURL(/docs\/guide\.md$/)
    await expect(page.locator('.prose')).toContainText('How to deploy the app')
    // History and a commit page with a diff.
    await page.getByRole('link', { name: 'History' }).click()
    await expect(page.getByRole('heading', { name: 'Commits' })).toBeVisible()
    await page.getByRole('link', { name: 'Initial app with a failing test' }).first().click()
    await expect(page.locator('.diff-summary')).toContainText('files changed')
    await expect(page.locator('.file-header').first()).toBeVisible()
  })

  test('edit a file through the API without a clone', async ({ page }) => {
    await page.goto('/app/acme/app/blob/main/docs/guide.md')
    await page.getByRole('button', { name: 'Edit' }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('Branch').fill('docs/edit-from-ui')
    await dialog.getByLabel('Contents').fill('# Guide\n\nEdited in the browser.\n')
    await dialog.getByRole('button', { name: /Commit to/ }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Committed through the API' })).toBeVisible()
    await expect(page).toHaveURL(/blob\/docs%2Fedit-from-ui\/docs\/guide\.md/)
    await expect(page.locator('.prose')).toContainText('Edited in the browser')
  })

  test('issues: list, keyboard navigation, detail, run the agent, watch the change land, see the ledger live', async ({ page, context }) => {
    test.setTimeout(240_000)
    // Open the ledger in a second tab first, so we can check it updates without a reload.
    const ledger = await context.newPage()
    await ledger.goto('/app/acme/app/ledger')
    await expect(ledger.getByRole('heading', { name: 'Ledger' })).toBeVisible()
    const before = await ledger.locator('.event-row').count()

    await page.goto('/app/acme/app/issues')
    await expect(page.getByRole('heading', { name: 'Issues' })).toBeVisible()
    expect(await page.locator('.list-row').count()).toBeGreaterThanOrEqual(2)
    // Filter, then j/k + Enter opens the issue from the keyboard.
    await page.getByLabel('Filter issues').fill('Greeting')
    await expect(page.locator('.list-row')).toHaveCount(1)
    await unfocus(page)
    await page.keyboard.press('j')
    await page.keyboard.press('j')
    await page.keyboard.press('k')
    await page.keyboard.press('Enter')
    await expect(page).toHaveURL(/\/issues\/1$/)
    await expect(page.locator('.page-head h1')).toContainText('Greeting should say Hello, Ore!')
    // The run-agent dialog explains the autonomy level.
    await page.getByRole('button', { name: 'Run agent on this issue' }).click()
    const dialog = page.getByRole('dialog')
    await expect(dialog).toContainText('L3 Land')
    await expect(dialog).toContainText('lands when the pipeline is green')
    await dialog.getByRole('button', { name: 'Start the loop' }).click()
    await expect(page).toHaveURL(/\/agents\/arun_/)
    // The loop runs live on the agent page.
    await expect(page.locator('.loop .step.current, .loop .step.done').first()).toBeVisible()
    await expect(page.locator('.pill', { hasText: 'completed' }).first()).toBeVisible({ timeout: 180_000 })
    await expect(page.locator('.loop .step.done')).toHaveCount(7)
    await expect(page.locator('.logview')).toContainText('demo agent: edited main.go')
    // The change it opened has landed (L3 lands when green).
    await page.getByRole('link', { name: /Greeting should say Hello, Ore!/ }).last().click()
    await expect(page).toHaveURL(/\/changes\/\d+/)
    await expect(page.locator('.pill', { hasText: 'merged' }).first()).toBeVisible({ timeout: 60_000 })
    await expect(page.getByText('agent-authored')).toBeVisible()
    // The ledger tab received the events without a reload.
    await expect.poll(async () => ledger.locator('.event-row').count(), { timeout: 60_000 }).toBeGreaterThan(before + 5)
    await expect(ledger.locator('.event-row.fresh').first()).toBeVisible()
    await expect(ledger.getByText('io.ore.change.merged').first()).toBeVisible()
    // The loop closed the issue when the change landed, and the issue page lists the run.
    await page.goto('/app/acme/app/issues/1')
    await expect(page.locator('.page-head .pill', { hasText: 'closed' }).first()).toBeVisible({ timeout: 30_000 })
    await expect(page.locator('aside .pill', { hasText: 'completed' }).first()).toBeVisible()
  })

  test('review a change: inline comment, structured finding, apply the suggested fix, land with a strategy', async ({ page }) => {
    const ch = await api<{ number: number }>('POST', '/api/v0/repos/acme/app/changes', { source_ref: 'refs/heads/feature/guide-polish', title: 'Polish the guide' }).catch(async () => (await api<Array<{ number: number; title: string; state: string }>>('GET', '/api/v0/repos/acme/app/changes')).find((c) => c.title === 'Polish the guide' && c.state === 'open')!)
    await page.goto(`/app/acme/app/changes/${ch.number}?tab=files`)
    await expect(page.locator('.diff-summary')).toContainText('files changed')
    // The rename shows as such.
    await expect(page.locator('.file-header', { hasText: 'new-name.md' })).toContainText('→')
    // An inline comment from a gutter number.
    await page.locator('.file-header', { hasText: 'docs/guide.md' }).scrollIntoViewIfNeeded()
    await page.locator('.line-grid .cell.num.clickable').first().click()
    await page.getByLabel('Inline comment').fill('Please mention the health check here.')
    await page.getByRole('button', { name: 'Comment', exact: true }).click()
    await expect(page.locator('.thread-box .comment')).toContainText('Please mention the health check here.')
    // A review with a finding carrying a suggested fix.
    await page.getByRole('button', { name: 'Review' }).click()
    const rd = page.getByRole('dialog')
    await rd.getByLabel('Request changes').check()
    await rd.getByRole('button', { name: 'Add finding' }).click()
    await rd.getByLabel('Path').fill('docs/guide.md')
    await rd.getByLabel('Lines', { exact: true }).fill('1')
    await rd.getByLabel('End line').fill('1')
    await rd.getByLabel('Message').fill('Title should name the service.')
    await rd.getByLabel('Suggested fix (replaces the lines)').fill('# Guide to deploying app')
    await rd.getByRole('button', { name: 'Submit review' }).click()
    await expect(rd).toBeHidden()
    await page.goto(`/app/acme/app/changes/${ch.number}`)
    await expect(page.locator('.finding-sev')).toBeVisible()
    await expect(page.getByText('does not count')).toHaveCount(0)
    await page.getByRole('button', { name: 'Apply fix' }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Fix applied' })).toBeVisible()
    // A new patch set exists; approvals reset; land with the queue strategy.
    await expect(page.getByText('Patch sets · 2')).toBeVisible({ timeout: 20_000 })
    await page.getByRole('button', { name: 'Land' }).click()
    const ld = page.getByRole('dialog')
    await expect(ld).toContainText('Queue')
    await expect(ld).toContainText('Optimistic')
    await ld.getByLabel(/Queue/).check()
    await ld.getByRole('button', { name: /Land with queue/ }).click()
    await expect(page.locator('.pill', { hasText: 'merged' }).first()).toBeVisible({ timeout: 30_000 })
  })

  test('pipelines: run detail with plan, log search and jump to failure on a 50,000-line log', async ({ page }) => {
    test.setTimeout(180_000)
    const run = await api<{ id: string }>('POST', '/api/v0/repos/acme/app/runs', { ref: 'refs/heads/feature/noisy' })
    await page.goto(`/app/acme/app/pipelines/${run.id}`)
    await expect(page.locator('.page-head .pill', { hasText: /failed|error/ }).first()).toBeVisible({ timeout: 120_000 })
    await expect(page.locator('.dag .task')).toHaveCount(1)
    await expect(page.locator('.logview .pill', { hasText: /lines/ })).toContainText(/50,00\d lines|50\d{3} lines/, { timeout: 60_000 })
    await page.getByRole('button', { name: 'Jump to failure' }).click()
    await expect(page.locator('.log-line.err')).toBeVisible()
    await page.getByLabel('Search log').fill('49999')
    await expect(page.getByText('1 / 1')).toBeVisible()
    // Search-as-you-type scrolls to the first match, so the virtualized row is in the DOM.
    await expect(page.locator('.log-line.match')).toContainText('49999')
    await page.getByLabel('Search log').press('Enter')
    await expect(page.locator('.log-line.current')).toContainText('49999')
  })

  test('deployments: environment cards, deploy request and DORA panel', async ({ page }) => {
    await page.goto('/app/acme/app/deployments')
    await expect(page.getByRole('heading', { name: 'Deployments', exact: true })).toBeVisible()
    await expect(page.locator('.env-card', { hasText: 'production' })).toBeVisible()
    await expect(page.locator('.env-card', { hasText: 'preview' })).toBeVisible()
    await expect(page.getByText('DORA · last 30 days')).toBeVisible()
    await expect(page.getByText('Deployment frequency')).toBeVisible()
    await page.locator('.env-card', { hasText: 'preview' }).getByRole('button', { name: 'Deploy' }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Deploy' }).click()
    await expect(page.getByRole('status').filter({ hasText: /Deployment of/ })).toBeVisible()
    await expect(page.locator('.timeline-item').first()).toBeVisible()
  })

  test('settings: autonomy level with explanation, review policy, tokens shown once, MCP instructions', async ({ page }) => {
    await page.goto('/app/acme/app/settings')
    await expect(page.getByText('L3 Land (current)')).toBeVisible()
    await page.getByLabel(/L2 Author/).check()
    await expect(page.getByText('Nothing lands without a human.')).toBeVisible()
    await page.getByLabel('Reason (recorded on the ledger)').fill('e2e')
    await page.getByRole('button', { name: 'Set level L2' }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Autonomy set to L2' })).toBeVisible()
    await page.getByLabel(/L3 Land/).check()
    await page.getByRole('button', { name: 'Set level L3' }).click()
    await page.getByRole('link', { name: 'Review policy' }).click()
    await expect(page.getByLabel('Required approvals')).toBeVisible()
    await page.goto('/app/settings/tokens')
    await page.getByRole('button', { name: 'New token' }).click()
    await page.getByLabel('Name').fill('e2e-token')
    await page.getByRole('dialog').getByRole('button', { name: 'Create' }).click()
    await expect(page.getByText('Copy your token now')).toBeVisible()
    await expect(page.locator('.copybox code')).toContainText('ore_')
    await page.getByRole('button', { name: 'I saved it' }).click()
    await expect(page.getByRole('cell', { name: 'e2e-token', exact: true }).first()).toBeVisible()
    await page.goto('/app/settings/mcp')
    await expect(page.getByText('claude mcp add')).toBeVisible()
  })
})
